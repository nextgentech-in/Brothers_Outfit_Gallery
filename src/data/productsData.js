function daysAgo(n) {
  const d = new Date();
  d.setDate(d.getDate() - n);
  d.setHours(10, 0, 0, 0);
  return d.toISOString();
}

function hoursFromNow(n) {
  const d = new Date();
  d.setTime(d.getTime() + n * 60 * 60 * 1000);
  return d.toISOString();
}

